"""
Plotting tools for the hosono code.

includes
    plot3dVar2dSlice
        plots 2D slice of 2D or 3D data

    plot3dVar1dSlice
        plots 1D slice of 1D, 2D, or 3D data

    get_final_output_file_idx
        gets the final data file index from a collection
        of data files generated by a single run of hosono
"""

import h5py
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.colors as colors
from matplotlib.collections import QuadMesh
import glob

def draw2dData(x, y, var_data, colormap, logOfData=False, contourPlot=False,
               contourBackground=False, nLevels=30):
    """
    Draw 2D data on the current axes.

    Draws a pcolormesh, contour lines colored by the colormap, or (with
    contourBackground) black contour lines over the pcolormesh. logOfData
    puts both the coloring and the contour levels on a log scale.
    nLevels sets the number of contour lines.
    Returns the object to build the colorbar from and a save name prefix.
    """
    orig_map = plt.get_cmap(colormap)
    norm = colors.LogNorm() if logOfData else None

    if not contourPlot:
        return plt.pcolormesh(x, y, var_data, cmap=orig_map, norm=norm), ''

    if contourBackground:
        color_plot = plt.pcolormesh(x, y, var_data, cmap=orig_map, norm=norm)
        saveName = '_contoursbg_'
    else:
        color_plot = None
        saveName = '_contours_'

    # log spaced levels can only be built from the positive data
    level_data = var_data[var_data > 0] if logOfData else var_data
    if level_data.size == 0 or level_data.min() == level_data.max():
        # contour needs increasing levels, so fall back to pcolormesh for a constant field
        if color_plot is None:
            color_plot = plt.pcolormesh(x, y, var_data, cmap=orig_map, norm=norm)
        return color_plot, saveName

    vmin, vmax = level_data.min(), level_data.max()
    if logOfData:
        levels = np.geomspace(vmin, vmax, nLevels)
        norm = colors.LogNorm(vmin, vmax)
    else:
        levels = np.linspace(vmin, vmax, nLevels)

    if contourBackground:
        plt.contour(x, y, var_data, levels=levels, colors='k', linewidths=0.6)
    else:
        color_plot = plt.contour(x, y, var_data, levels=levels, cmap=orig_map,
                                 norm=norm, linewidths=0.6)

    return color_plot, saveName

def plot2dVar2dSlice(var: str, relPathBaseName: str, timeIdx: int,
                     contourPlot=False, contourBackground=False, nContourLevels=30,
                     relSavePath='./', axeq=True, logOfData=False,
                     pdfSave=False, custom_clim=None, colormap='jet', showPlot=False,
                     savePlot=True):

    # get the plot file corresponding to timeIdx
    # relPathBaseName = relPathBaseName+str(00000+timeIdx)+'.h5'
    relPathBaseName = f'{relPathBaseName}{timeIdx:05d}.h5'

    # create hdf5 file object
    f = h5py.File(relPathBaseName)

    # getting simulation time at this plot file
    sim_time = f["time"][0]

    # getting the bounds in x and y of the computational domain
    xmin = f["xmin"][0]
    xmax = f["xmax"][0]
    ymin = f["ymin"][0]
    ymax = f["ymax"][0]
    nx = f["nx"][0]
    ny = f["ny"][0]

    # get data corresponding to the variable string stored in var
    var_dset = f[var]
    var_data = np.array(var_dset)

    # getting the grid on which to plot
    xx = np.linspace(xmin, xmax, nx)
    yy = np.linspace(ymin, ymax, ny)

    # create plot
    fig, ax = plt.subplots()  # create figure and axes

    # do different things depending on which direction we are slicing normal to
    titleStr = f'{var} t={sim_time:.4e}'
    x = xx
    y = yy
    var_data = var_data[:, :]
    coord_idxs = [0, 1]

    # Define font properties for plot
    title_font = {'size': 18}
    label_font = {'size': 14}
    # plot the data
    color_plot, saveName = draw2dData(x, y, var_data, colormap, logOfData,
                                      contourPlot, contourBackground,
                                      nContourLevels)
    plt.colorbar(color_plot, label=var)  # this shows the colorbar
    axis_labels = ['x', 'y', 'z']
    ax.set_xlabel(axis_labels[coord_idxs[0]], fontdict=label_font)
    ax.set_ylabel(axis_labels[coord_idxs[1]], fontdict=label_font)
    if axeq:
        ax.axis('equal')
    ax.set_title(titleStr, fontdict=title_font)
    plt.tight_layout()  # this prevents the x and y labels from being clipped
    saveName = saveName + var+'_t'+str(timeIdx).zfill(4)
    if custom_clim and len(custom_clim)==2:
        color_plot.set_clim(custom_clim[0], custom_clim[1])
    if savePlot:
        if pdfSave:
            # hide pcolormesh cell edges, but leave contour lines alone
            if isinstance(color_plot, QuadMesh):
                color_plot.set_linewidth(0.0001)
            plt.savefig(relSavePath+saveName+".pdf")
        else:
            plt.savefig(relSavePath+saveName+".png")
    if showPlot:
        plt.show()
    plt.close()

    return

def plot3dVar2dSlice(var: str, relPathBaseName: str, timeIdx: int,
                     sliceNormalTo: str, sliceIdx=-1, contourPlot=False,
                     contourBackground=False, nContourLevels=30, relSavePath='./', axeq=True, logOfData=False, pdfSave=False,
                     custom_clim=False, colormap='jet', showPlot=False,
                     savePlot=True):

    # get the plot file corresponding to timeIdx
    # relPathBaseName = relPathBaseName+str(10000+timeIdx)+'.h5'
    relPathBaseName = f'{relPathBaseName}{timeIdx:05d}.h5'

    # create hdf5 file object
    f = h5py.File(relPathBaseName)

    # getting simulation time at this plot file
    sim_time = f["time"][0]

    # getting the bounds in x and y of the computational domain
    xmin = f["xmin"][0]
    xmax = f["xmax"][0]
    ymin = f["ymin"][0]
    ymax = f["ymax"][0]
    zmin = f["zmin"][0]
    zmax = f["zmax"][0]
    nx = f["nx"][0]
    ny = f["ny"][0]
    nz = f["nz"][0]

    # get data corresponding to the variable string stored in var
    var_dset = f[var]
    var_data = np.array(var_dset)

    # getting the grid on which to plot
    xx = np.linspace(xmin, xmax, nx)
    yy = np.linspace(ymin, ymax, ny)
    zz = np.linspace(zmin, zmax, nz)

    # create plot
    fig, ax = plt.subplots()  # create figure and axes

    # set slice index
    if sliceNormalTo == 'z':
        N_normalDir = nz
    elif sliceNormalTo == 'y':
        N_normalDir = ny
    elif sliceNormalTo == 'x':
        N_normalDir = nx
    if sliceIdx > N_normalDir:
        print("sliceIdx is too large. Please make sure it is within bounds.")
        quit()
    elif sliceIdx < 0:
        sliceIdx = int(N_normalDir/2)

    # do different things depending on which direction we are slicing normal to
    titleStr = f'{var} t={sim_time:.4e}'
    if sliceNormalTo == 'z':
        x = xx
        y = yy
        grid_normalDir = zz
        var_data = var_data[sliceIdx, :, :]
        coord_idxs = [0, 1]
        titleStr = titleStr+f' z = {grid_normalDir[sliceIdx]:.2f}'
    elif sliceNormalTo == 'y':
        x = xx
        y = zz
        grid_normalDir = yy
        var_data = var_data[:, sliceIdx, :]
        coord_idxs = [0, 2]
        titleStr = titleStr+f' y = {grid_normalDir[sliceIdx]:.2f}'
    elif sliceNormalTo == 'x':
        x = yy
        y = zz
        grid_normalDir = xx
        var_data = var_data[:, :, sliceIdx]
        coord_idxs = [1, 2]
        titleStr = titleStr+f' x = {grid_normalDir[sliceIdx]:.2f}'
    else:
        print("sliceNormalTo given invalid parameter value of "+sliceNormalTo)
        return

    # Define font properties for plot
    title_font = {'size': 18}
    label_font = {'size': 14}
    # plot the data
    color_plot, saveName = draw2dData(x, y, var_data, colormap, logOfData,
                                      contourPlot, contourBackground,
                                      nContourLevels)
    plt.colorbar(color_plot, label=var)  # this shows the colorbar
    axis_labels = ['x', 'y', 'z']
    ax.set_xlabel(axis_labels[coord_idxs[0]], fontdict=label_font)
    ax.set_ylabel(axis_labels[coord_idxs[1]], fontdict=label_font)
    if axeq:
        ax.axis('equal')
    ax.set_title(titleStr, fontdict=title_font)
    plt.tight_layout()  # this prevents the x and y labels from being clipped
    saveName = saveName + var+'_'+sliceNormalTo+str(sliceIdx)+'_t'+str(timeIdx).zfill(4)
    if custom_clim and len(custom_clim)==2:
        color_plot.set_clim(custom_clim[0], custom_clim[1])
    if savePlot:
        if pdfSave:
            # hide pcolormesh cell edges, but leave contour lines alone
            if isinstance(color_plot, QuadMesh):
                color_plot.set_linewidth(0.0001)
            plt.savefig(relSavePath+saveName+".pdf")
        else:
            plt.savefig(relSavePath+saveName+".png")
    if showPlot:
        plt.show()
    plt.close()

    return


def plot3dVar1dSlice(var: str, relPathBaseName: str, timeIdx: int,
                      sliceAlong: str, sliceIdx1=-1, sliceIdx2=-1,
                      relSavePath='./', axeq=False, logOfData=False,
                      showPlot=False, savePlot=True, pdfSave=False):
    """
    Generate a 1D plot of a given variable vs position from a hosono data file.

    Uses the h5py library to create a 1D plot of a variable vs position.
    Can specify a number of things to alter the plot.
    """
    # get the plot file corresponding to timeIdx
    relPathBaseName = relPathBaseName+str(10000+timeIdx)+'.h5'

    # create hdf5 file object
    f = h5py.File(relPathBaseName)

    # getting simulation time at this plot file
    sim_time = f["time"][0]

    # getting the bounds in x and y of the computational domain
    xmin = f["xmin"][0]
    xmax = f["xmax"][0]
    ymin = f["ymin"][0]
    ymax = f["ymax"][0]
    zmin = f["zmin"][0]
    zmax = f["zmax"][0]
    nx = f["nx"][0]
    ny = f["ny"][0]
    nz = f["nz"][0]

    fig, ax = plt.subplots()  # create figure and axes
    # Define font properties for plot
    title_font = {'size': 18}
    label_font = {'size': 14}

    # set sliceIdx1 and sliceIdx2
    if sliceAlong == "x":
        N_normal1 = ny
        N_normal2 = nz
        sliceDir1 = "y"
        sliceDir2 = "z"
    elif sliceAlong == "y":
        N_normal1 = nx
        N_normal2 = nz
        sliceDir1 = "x"
        sliceDir2 = "z"
    elif sliceAlong == "z":
        N_normal1 = nx
        N_normal2 = ny
        sliceDir1 = "x"
        sliceDir2 = "y"
    if sliceIdx1 > N_normal1:
        print("sliceIdx1 is too large. Please make sure it is within bounds.")
        quit()
    elif sliceIdx1 < 0:
        sliceIdx1 = int(N_normal1/2)
    if sliceIdx2 > N_normal2:
        print("sliceIdx2 is too large. Please make sure it is within bounds.")
        quit()
    elif sliceIdx2 < 0:
        sliceIdx2 = int(N_normal2/2)

    # get data for the variable string stored in var
    var_dset = f[var]
    var_data = np.array(var_dset)
    if sliceAlong == "x":
        var_data = var_data[sliceIdx2, sliceIdx1, :]
        grid = np.linspace(xmin, xmax, nx)
        ax.set_xlabel("x", fontdict=label_font)
    elif sliceAlong == "y":
        var_data = var_data[sliceIdx2, :, sliceIdx1]
        grid = np.linspace(ymin, ymax, ny)
        ax.set_xlabel("y", fontdict=label_font)
    elif sliceAlong == "z":
        var_data = var_data[:, sliceIdx2, sliceIdx1]
        grid = np.linspace(zmin, zmax, nz)
        ax.set_xlabel("z", fontdict=label_font)
    else:
        print("please choose a valid direction to slice along to")
        return

    # plot the data
    if logOfData:
        ax.semilogy(grid, var_data, "+")
    else:
        ax.plot(grid, var_data, "+")
    ax.set_ylabel(var, fontdict=label_font)
    if axeq:
        ax.axis('equal')
    titleStr = f'{var} t={sim_time:.4e}'
    ax.set_title(titleStr, fontdict=title_font)
    plt.tight_layout()  # this prevents the x and y labels from being clipped
    sliceInfo = sliceDir1+str(sliceIdx1)+sliceDir2+str(sliceIdx2)
    saveName = '1D_slice_'+var+'_'+sliceInfo+'_t'+str(timeIdx).zfill(4)
    if showPlot:
        plt.show()
    if savePlot:
        if pdfSave:
            plt.savefig(relSavePath+saveName+".pdf")
        else:
            plt.savefig(relSavePath+saveName+".png")
    plt.close()

    return


def get_final_output_file_idx(data_file_path):
    """
    Get index of last data file in collection of data files.

    Given the path (including base name) of a set of data files
    will return the index corresponding to the final output.
    """
    files_glob = glob.glob(data_file_path+'*')

    return len(files_glob)


