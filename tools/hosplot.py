# PYTHON_ARGCOMPLETE_OK
'''
Command line tool for plotting hdf5 data from
the hosono FVM code.
'''
import argparse
import glob
import os
import re
from pathlib import Path

# tab completion is optional, hosplot runs fine without argcomplete
try:
    import argcomplete
except ImportError:
    argcomplete = None


# tab completion helpers. These run on every tab press so heavy
# imports are done inside them rather than at the top of the file.
def datfile_completer(prefix, **kwargs):
    '''Complete directories and data file base names, e.g. data/run.'''
    completions = set()
    for path in glob.glob(prefix+'*'):
        if os.path.isdir(path):
            completions.add(path+'/')
        elif re.search(r'\d{5}\.h5$', path):
            completions.add(path[:-len('00000.h5')])
    return sorted(completions)


def var_completer(prefix, parsed_args, **kwargs):
    '''Complete the names of the 2D/3D datasets in the first data file.'''
    import h5py
    files = sorted(glob.glob(parsed_args.datfile+'[0-9]'*5+'.h5'))
    if not files:
        return []
    with h5py.File(files[0], 'r') as f:
        return [k for k in f if isinstance(f[k], h5py.Dataset)
                and f[k].ndim >= 2 and k.startswith(prefix)]


def cmap_completer(prefix, **kwargs):
    '''Complete matplotlib colormap names.'''
    import matplotlib
    return [c for c in matplotlib.colormaps if c.startswith(prefix)]


# create argument parser object
parser = argparse.ArgumentParser(prog='hosplot',
                                 description='Plots data from hdf5 format '
                                 'generated by the hosono code.',
                                 epilog='Written by Sean Riedel')

# add arguments to the parser object
parser.add_argument('datfile', help='Relative path to one of the data files.'
                    ).completer = datfile_completer
parser.add_argument('var', nargs='+',
                    help='Variable(s) you wish to plot, e.g., pres for pressure.'
                    ).completer = var_completer
parser.add_argument('-s', '--saveplot', action='store_true',
                    help='Save the generated plot(s)')
parser.add_argument('-d', '--display', action='store_true',
                    help='Show the generated plot(s)')
parser.add_argument('-n', '--direction', default='z', choices=['x', 'y', 'z'],
                    help='Normal direction in 2D, axis to plot in 1D')
parser.add_argument('-i', '--idx', type=int, default=-1,
                    help='Specify a plot file index.'
                    ' Defaults to final output.')
parser.add_argument('-a', '--alltimes', action='store_true',
                    help='Plot all data files for this run.')
parser.add_argument('-f', '--freq', type=int, default=1,
                    help='Plot data files through time with frequency '
                    'given by freq. Requires --alltimes to have any effect.')
parser.add_argument('-D', '--dim', type=int, default=2,
                    help='1D plot or 2D plot of (up to 3D) data')
parser.add_argument('--hdf5_data_dim', type=int, default=2,
                    help='Dimension of the data in the hdf5 output. '
                    'For data created by Hosono this is always 3 but for a truly 2D '
                    'code this is 2.')
parser.add_argument('--sliceIdx1', type=int, default=-1,
                    help='')
parser.add_argument('--sliceIdx2', type=int, default=-1,
                    help='')
parser.add_argument('--axneq', action='store_false',
                    help='Use this flag to stop the axes from havin equal '
                    'aspect ratio.')
parser.add_argument('--logplot', action='store_true',
                    help='whether to plot data on log scale')
parser.add_argument('-p', '--savepath', default='./images/',
                    help='Relative path to dir where plots should be saved. '
                    'Defaults to ./images/varname/ so for example ./images/pres/')
parser.add_argument('-N', '--savename',
                    help='Set the base name of file to save plot(s) to')
parser.add_argument('--pdfsave', action='store_true',
                    help='Whether or not to save the plot(s) as a pdf.')
parser.add_argument('--cmap', default='jet',
                    help='Specify a color map to use. '
                    "Defaults to 'jet'.").completer = cmap_completer
parser.add_argument('--clim', nargs='+', type=float, default=0.0,
                    help='Specify limits for the colorbar.')
parser.add_argument('--contours', action='store_true',
                    help='create a contour plot')
parser.add_argument('--contourbg', action='store_true',
                    help='Black contour lines over the colormap coloring. '
                    'Implies --contours.')
parser.add_argument('--nlevels', type=int, default=30,
                    help='Number of contour lines to draw with --contours '
                    'or --contourbg. Defaults to 30.')

# answer a tab completion request if there is one (exits when it does)
if argcomplete is not None:
    # zsh shows each completion on one line and cuts off long help
    # text, so only show the first sentence when completing
    if '_ARGCOMPLETE' in os.environ:
        for action in parser._actions:
            if action.help:
                action.help = action.help.split('. ')[0].rstrip('.')
    argcomplete.autocomplete(parser)

# parse the command line arguments to the script
args = parser.parse_args()

# imported here so tab completion doesn't pay for matplotlib/h5py
import hosonoPlotUtils as pu

# get run name and base data file name
base_name = args.datfile
run_name = base_name.split('/')[-1]

if args.nlevels < 1:
    parser.error('--nlevels must be at least 1')

# contour lines over the coloring is still a contour plot
if args.contourbg:
    args.contours = True

# make sure to at least display a plot
if not args.saveplot and not args.display:
    args.display = True

# plot all outputs if requested
nFiles = pu.get_final_output_file_idx(base_name)
# files are numbered 00000, 00001, 00002, ....
# so nFiles is one more than the index present 
# in the name of the last file (since we started 
# at 00000)
if args.alltimes:
    plt_indicies = range(0, nFiles, args.freq)
elif args.idx >= 0:
    plt_indicies = [args.idx]
else:
    plt_indicies = [nFiles-1]

# change direction to x if making a 1D plot
if args.dim == 1:
    args.direction = 'x'

# loop over each variable to plot
for var_to_plot in args.var:

    # ensure default naming convention for where plots are saved
    save_path = args.savepath+'/'+var_to_plot+'/'


    # check if save_path exists. If it doesn't then create it
    if args.saveplot:
        Path(save_path).mkdir(parents=True, exist_ok=True)

    # append what we want the image file to be called to end of save_path
    if args.savename is None:
        save_path = save_path+run_name
    else:
        save_path = save_path+args.savename

    # define plotting functions and pass in arguments
    def plot1D(i):
        pu.plot3dVar1dSlice(var_to_plot, base_name, i, args.direction,
                            savePlot=args.saveplot, showPlot=args.display,
                            relSavePath=save_path, logOfData=args.logplot,
                            sliceIdx1=args.sliceIdx1, sliceIdx2=args.sliceIdx2,
                            pdfSave=args.pdfsave)
        return

    if args.hdf5_data_dim == 3:
        def plot2D(i):
            pu.plot3dVar2dSlice(var_to_plot, base_name, i, args.direction,
                                contourPlot=args.contours,
                                contourBackground=args.contourbg,
                                nContourLevels=args.nlevels,
                                savePlot=args.saveplot, showPlot=args.display,
                                relSavePath=save_path, logOfData=args.logplot,
                                pdfSave=args.pdfsave, axeq=args.axneq,
                                colormap=args.cmap,
                                custom_clim=args.clim)
            return
    else:
        def plot2D(i):
            pu.plot2dVar2dSlice(var_to_plot, base_name, i, 
                                contourPlot=args.contours,
                                contourBackground=args.contourbg,
                                nContourLevels=args.nlevels,
                                savePlot=args.saveplot, showPlot=args.display,
                                relSavePath=save_path, logOfData=args.logplot,
                                pdfSave=args.pdfsave, axeq=args.axneq,
                                colormap=args.cmap,
                                custom_clim=args.clim)

    if args.dim == 1:
        def plotFunc(i):
            plot1D(i)
            return
    else:
        def plotFunc(i):
            plot2D(i)
            return


    # generate plots
    for i in plt_indicies:
        plotFunc(i)

    # if last plot wasn't generated when creating
    # multiple plots, create it now
    if len(plt_indicies) > 1 and i < nFiles-1:
        plotFunc(nFiles)


